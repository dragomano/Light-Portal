namespace LightPortal\Plugins\MaterialDesignIcons;

use LightPortal\Assets\ExternalCss;
use LightPortal\Enums\License;
use LightPortal\Enums\PluginType;
use LightPortal\Plugins\CreditsFactory;
use LightPortal\Plugins\Event;
use LightPortal\Plugins\PluginAttribute;
use LightPortal\Plugins\Plugin;

if (! defined('LP_NAME'))
	die('No direct access...');

/**
 * Generated by PluginMaker
 */
#[PluginAttribute(type: PluginType::ICONS)]
class MaterialDesignIcons extends Plugin
{
	private string $prefix = 'mdi mdi-';

	public function init(): void
	{
		$this->loadExternalResources(new ExternalCss(
			'https://cdn.jsdelivr.net/npm/@mdi/font@7/css/materialdesignicons.min.css'
		));
	}

	public function prepareIconList(Event $e): void
	{
		$mdIcons = $this->cache()->remember('all_md_icons', function () {
			$content = file_get_contents('https://raw.githubusercontent.com/Templarian/MaterialDesign/master/meta.json');
			$json = json_decode($content);

			$icons = [];
			foreach ($json as $icon) {
				$icons[] = $this->prefix . $icon->name;
			}

			return $icons;
		}, 30 * 24 * 60 * 60);

		$e->args->icons = array_merge($e->args->icons, $mdIcons);
	}

	public function credits(Event $e): void
	{
		$e->args->links[$this->name] = CreditsFactory::make()
			->title('Material Design Icons')
			->link('https://pictogrammers.com/library/mdi/')
			->author('Pictogrammers')
			->license(License::PictogrammersFree)
			->toArray();
	}
}
