namespace LightPortal\Plugins\Carve;

use Bugo\Compat\Utils;
use LightPortal\Enums\License;
use LightPortal\Enums\PluginType;
use LightPortal\Plugins\Carve\SMF\AdmonitionExtension;
use LightPortal\Plugins\CreditsFactory;
use LightPortal\Plugins\Event;
use LightPortal\Plugins\Plugin;
use LightPortal\Plugins\PluginAttribute;
use MarkupCarve\Carve\CarveConverter;
use MarkupCarve\Carve\Event\RenderEvent;
use MarkupCarve\Carve\Extension\AutolinkExtension;
use MarkupCarve\Carve\Extension\CodeGroupExtension;
use MarkupCarve\Carve\Extension\ColorSwatchExtension;
use MarkupCarve\Carve\Extension\DetailsExtension;
use MarkupCarve\Carve\Extension\ExternalLinksExtension;
use MarkupCarve\Carve\Extension\FencedRenderExtension;
use MarkupCarve\Carve\Extension\GlossaryExtension;
use MarkupCarve\Carve\Extension\InlineFootnotesExtension;
use MarkupCarve\Carve\Extension\MathBlockExtension;
use MarkupCarve\Carve\Extension\SemanticSpanExtension;
use MarkupCarve\Carve\Extension\SpoilerExtension;
use MarkupCarve\Carve\Extension\TabNormalizeExtension;
use MarkupCarve\Carve\Extension\TabsExtension;
use MarkupCarve\Carve\Node\Inline\Link;

if (! defined('LP_NAME'))
	die('No direct access...');

/**
 * Generated by PluginMaker
 */
#[PluginAttribute(type: PluginType::PARSER)]
class Carve extends Plugin
{
	public function init(): void
	{
		Utils::$context['lp_content_types'][$this->name] = $this->getCamelName();
	}

	public function parseContent(Event $e): void
	{
		$e->args->content = $this->getParsedContent($e->args->content);
	}

	public function credits(Event $e): void
	{
		$e->args->links[$this->name] = CreditsFactory::make()
			->title('carve-php')
			->link('https://github.com/markup-carve/carve-php')
			->author('Mark Scherer')
			->license(License::Mit, 'https://github.com/markup-carve/carve-php#MIT-1-ov-file')
			->toArray();
	}

	private function getParsedContent(string $text): string
	{
		require_once __DIR__ . '/vendor/autoload.php';

		$converter = new CarveConverter();

		$this->registerExtensions($converter);
		$this->registerRenderListeners($converter);
		$this->addOutputTransformers($converter);

		return $converter->convert(Utils::htmlspecialcharsDecode($text));
	}

	private function registerExtensions(CarveConverter $converter): void
	{
		$converter->addExtension(new AutolinkExtension());
		$converter->addExtension(new ExternalLinksExtension());
		$converter->addExtension(new InlineFootnotesExtension());
		$converter->addExtension(new GlossaryExtension());
		$converter->addExtension(new SemanticSpanExtension());
		$converter->addExtension(new TabNormalizeExtension());
		$converter->addExtension(new ColorSwatchExtension());
		$converter->addExtension(new AdmonitionExtension(titles: $this->admonitionTitles()));
		$converter->addExtension(new DetailsExtension());
		$converter->addExtension(new SpoilerExtension());
		$converter->addExtension(new TabsExtension());
		$converter->addExtension(new CodeGroupExtension());
		$converter->addExtension(new MathBlockExtension());
		$converter->addExtension(FencedRenderExtension::mermaid());
		$converter->addExtension(FencedRenderExtension::chart());
	}

	private function registerRenderListeners(CarveConverter $converter): void
	{
		$converter->on('render.block_quote', function (RenderEvent $event): void {
			$event->getNode()->addClass('bbc_standard_quote');
		});

		$converter->on('render.code_block', function (RenderEvent $event): void {
			$node     = $event->getNode();
			$existing = $node->getAttribute('class') ?? '';

			$node->setAttribute('class', trim('bbc_code ' . $existing));
		});

		$converter->on('render.heading', function (RenderEvent $event): void {
			$event->getNode()->addClass('titlebg');
		});

		$converter->on('render.list', function (RenderEvent $event): void {
			$event->getNode()->addClass('bbc_list');
		});

		$converter->on('render.table', function (RenderEvent $event): void {
			$event->getNode()->addClass('table_grid');
		});

		$converter->on('render.definition_list', function (RenderEvent $event): void {
			$event->getNode()->addClass('descbox');
		});

		$converter->on('render.image', function (RenderEvent $event): void {
			$event->getNode()->addClass('bbc_img');
		});

		$converter->on('render.link', function (RenderEvent $event): void {
			/** @var Link $node */
			$node = $event->getNode();
			$dest = $node->getDestination() ?? '';

			$node->addClass(str_contains($dest, 'mailto:') ? 'bbc_email' : 'bbc_link');
		});
	}

	private function admonitionTitles(): array
	{
		$titles = $this->txt['admonition_titles'] ?? [];

		return is_array($titles) ? $titles : [];
	}

	private function addOutputTransformers(CarveConverter $converter): void
	{
		$converter->addOutputTransformer(function (string $html): string {
			return preg_replace(
				'/<li>((?:(?!<\/li>).)*<input type="checkbox"[^>]*>)/',
				'<li style="list-style: none; margin-left: -20px">$1',
				$html
			);
		});

		$converter->addOutputTransformer(function (string $html): string {
			$html = preg_replace_callback(
				'/<thead>(.*?)<\/thead>/s',
				function (array $m) {
					return '<thead>' . preg_replace('/<tr>/', '<tr class="title_bar">', $m[1]) . '</thead>';
				},
				$html
			);

			return preg_replace_callback(
				'/<tbody>(.*?)<\/tbody>/s',
				function (array $m) {
					return '<tbody>' . preg_replace('/<tr>/', '<tr class="windowbg">', $m[1]) . '</tbody>';
				},
				$html
			);
		});
	}
}
